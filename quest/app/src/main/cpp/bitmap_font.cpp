void Canvas::fill(int32_t x, int32_t y, int32_t fw, int32_t fh, uint32_t c) const {
    const int32_t x0 = std::max(x, 0), y0 = std::max(y, 0);
    const int32_t x1 = std::min(x + fw, w), y1 = std::min(y + fh, h);
    for (int32_t yy = y0; yy < y1; ++yy) std::fill(px + yy * stride + x0, px + yy * stride + x1, c);
}

int32_t Canvas::textWidth(const char* s, int32_t scale) {
    int32_t chars = 0;
    while (*s) {
        nextCodepoint(s);
        ++chars;
    }
    return chars * 6 * scale;
}

void Canvas::text(int32_t x, int32_t y, int32_t scale, const char* s, uint32_t fg) const {
    for (; *s; x += 6 * scale) {
        const uint8_t* rows = glyphRows(fontChar(nextCodepoint(s)));
        for (int32_t r = 0; r < 7; ++r) {
            for (int32_t col = 0; col < 5; ++col) {
                if (rows[r] & (0x10 >> col)) fill(x + col * scale, y + r * scale, scale, scale, fg);
            }
        }
    }
}

