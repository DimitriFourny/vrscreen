constexpr uint8_t kUnknownGlyph[7] = {0x1F, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1F};

const uint8_t* glyphRows(char c) {
    if (c >= 'a' && c <= 'z') c = static_cast<char>(c - 'a' + 'A');
    for (const Glyph& g : kFont) {
        if (g.c == c) return g.rows;
    }
    return kUnknownGlyph;
}

